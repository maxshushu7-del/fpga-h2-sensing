`timescale 1ns/1ps
// =1: legacy raw; =2: legacy zoom; =3: automatic direct-low-band / high-band zoom.
// No feedback control/DAC, no claimed calibrated ADC rate or Hz-level accuracy.
module measurement_improved #(
    parameter integer ALGORITHM_VERSION=1, ADC_CHANNEL=1, FFT_LOG2=12,
    parameter integer WINDOW_ENABLE=1, DECIMATION=250,
    parameter integer ADC_SAMPLE_RATE_HZ=250000000,
    parameter integer MIN_SIGNAL_HZ=(ALGORITHM_VERSION==3 ? 5000 : 1000000),
    parameter integer HIGH_BAND_MIN_HZ=400000,
    parameter integer LOW_BAND_MAX_HZ=450000,
    // Verification-only knob; keep0 in all hardware builds.
    parameter integer SIM_IDLE_FFT_PAUSE=0,
    // Legacy benches retain coarse-before-every-frame by default. The new
    // hardware top enables bounded reuse of a previously validated passband.
    parameter integer TRACKING_ENABLE=0,
    parameter integer TRACK_RECHECK_FRAMES=4,
    parameter integer TRACK_EDGE_HZ=80000,
    parameter integer FRAME_GAP_CYCLES=1000000,
    parameter integer TIMEOUT_CYCLES=2000000,
    parameter integer OUT_WIDTH=17+FFT_LOG2
) (
    input wire adc_clk, adc_rst_n,
    input wire signed [13:0] channel_a, channel_b,
    input wire proc_clk, proc_rst_n, enabled,
    output wire capture_active,
    output wire [FFT_LOG2-1:0] capture_address,
    output wire signed [OUT_WIDTH-1:0] fft_re, fft_im,
    output wire [FFT_LOG2-1:0] fft_bin,
    output wire fft_valid, fft_last,
    output reg result_strobe, measurement_valid, fine_mode, low_mode,
    output reg result_fine_mode, result_low_mode, tracking_active,
    output reg [31:0] reacquire_count,
    output reg [31:0] frequency_hz, sequence_number,
    output reg [FFT_LOG2-1:0] peak_bin, coarse_bin,
    output reg signed [17:0] bin_offset_q16,
    output reg signed [31:0] fine_offset_hz,
    output reg [2*OUT_WIDTH:0] peak_power, noise_power,
    output reg [7:0] result_flags,
    output wire [31:0] clipped_samples,
    output wire protocol_error
);
    localparam integer N=1<<FFT_LOG2;
    localparam integer FINE_FS=ADC_SAMPLE_RATE_HZ/DECIMATION;
    localparam integer FINE_GUARD_HZ=FINE_FS/10;
    localparam integer ZOOM_MIN_BIN=(64'd1*FINE_FS*N+ADC_SAMPLE_RATE_HZ-1)/ADC_SAMPLE_RATE_HZ;
    // Explicit absolute E-drive tables; generated by tools/generate_tables.py.
    reg signed [15:0] hann[0:N-1];
    initial begin
        if (FFT_LOG2==12) $readmemh("E:/Codex/FPGA/projects/sensor_integrated_20261018/coefficients/hann_4096.mem",hann);
        else if (FFT_LOG2==10) $readmemh("E:/Codex/FPGA/projects/sensor_integrated_20261018/coefficients/hann_1024.mem",hann);
        else $error("Only 1024/4096 coefficient tables supplied");
        if (ALGORITHM_VERSION>=2 && ADC_SAMPLE_RATE_HZ%DECIMATION!=0)
            $error("Zoom requires integer Fs/decimation for current Hz conversion");
        if (ALGORITHM_VERSION>=2 && FFT_LOG2!=12)
            $error("Initial zoom release requires 4096-point coarse FFT for the narrowband guard");
        if (TRACK_RECHECK_FRAMES<1)
            $error("Tracking requires at least one filtered frame between coarse checks");
    end
    wire signed [13:0] selected_sample=ADC_CHANNEL==0 ? channel_a : channel_b;
    reg capture_start, capture_abort;
    reg [31:0] tuning_word;
    wire capture_busy, capture_done, capture_bad;
    wire signed [15:0] read_i,read_q,mean_i,mean_q;
    reg [FFT_LOG2-1:0] read_address;
    iq_snapshot #(.FFT_LOG2(FFT_LOG2),.DECIMATION(DECIMATION),.ENABLE_DDC(ALGORITHM_VERSION>=2)) u_snapshot (
        .adc_clk(adc_clk),.adc_rst_n(adc_rst_n),.adc_sample(selected_sample),
        .proc_clk(proc_clk),.proc_rst_n(proc_rst_n),.start(capture_start),
        .abort_capture(capture_abort),.fine_mode(fine_mode),.low_mode(low_mode),.tuning_word(tuning_word),
        .busy(capture_busy),.done(capture_done),.read_address(read_address),
        .read_i(read_i),.read_q(read_q),.mean_i(mean_i),.mean_q(mean_q),
        .clipped_samples(clipped_samples),.capture_bad(capture_bad),
        .capture_active(capture_active),.capture_address(capture_address));
    reg signed [15:0] hann_q,stream_i,stream_q;
    reg signed [31:0] product_i,product_q;
    // Fine baseband DC is a legitimate beat at the NCO frequency: do NOT remove it.
    wire signed [15:0] adjusted_i=fine_mode ? read_i : read_i-mean_i;
    wire signed [15:0] adjusted_q=fine_mode ? read_q : read_q-mean_q;
    always @(posedge proc_clk) hann_q<=hann[read_address];
    reg [3:0] state;
    localparam IDLE=0,START_CAPTURE=1,WAIT_CAPTURE=2,PRIME=3,MULTIPLY=4,
        ROUND=5,SEND=6,WAIT_RESULT=7,PUBLISH=8,RECOVER=9;
    wire sample_ready,configured;
    wire sample_valid=state==SEND;
    reg [3:0] core_reset_count;
    wire dsp_rst_n=proc_rst_n && core_reset_count==0;
    fft_stream_improved #(.FFT_LOG2(FFT_LOG2),.OUT_WIDTH(OUT_WIDTH),.SIM_IDLE_FFT_PAUSE(SIM_IDLE_FFT_PAUSE)) u_stream (
        .clk(proc_clk),.rst_n(dsp_rst_n),.sample_i(stream_i),.sample_q(stream_q),
        .sample_valid(sample_valid),.sample_last(read_address==N-1),.sample_ready(sample_ready),
        .configured(configured),.idle_capture(state==WAIT_CAPTURE),.fft_re(fft_re),.fft_im(fft_im),.fft_bin(fft_bin),
        .fft_valid(fft_valid),.fft_last(fft_last),.protocol_error(protocol_error));
    wire coarse_strobe,coarse_valid,coarse_interp;
    wire [FFT_LOG2-1:0] coarse_peak;
    wire signed [17:0] coarse_delta;
    wire signed [31:0] coarse_hz;
    wire coarse_in_band=(coarse_hz>=MIN_SIGNAL_HZ && coarse_hz<ADC_SAMPLE_RATE_HZ/2);
    wire [2*OUT_WIDTH:0] coarse_power,coarse_noise;
    wire frame_bad=capture_bad || clipped_samples!=0 || protocol_error;
    spectral_estimator #(.FFT_LOG2(FFT_LOG2),.OUT_WIDTH(OUT_WIDTH),
        .SAMPLE_RATE_HZ(ADC_SAMPLE_RATE_HZ),.WINDOW_ENABLE(WINDOW_ENABLE)) u_coarse (
        .clk(proc_clk),.rst_n(dsp_rst_n),.fft_re(fft_re),.fft_im(fft_im),.fft_bin(fft_bin),
        .fft_valid(fft_valid && !fine_mode && !low_mode),.fft_last(fft_last && !fine_mode && !low_mode),.frame_bad(frame_bad),
        .result_strobe(coarse_strobe),.measurement_valid(coarse_valid),.peak_bin(coarse_peak),
        .bin_offset_q16(coarse_delta),.frequency_offset_hz(coarse_hz),
        .peak_power(coarse_power),.noise_power(coarse_noise),.interp_valid(coarse_interp));
    wire fine_strobe,fine_valid,fine_interp;
    wire [FFT_LOG2-1:0] fine_peak;
    wire signed [17:0] fine_delta;
    wire signed [31:0] fine_hz;
    wire [2*OUT_WIDTH:0] fine_power,fine_noise;
    generate if (ALGORITHM_VERSION>=2) begin: g_zoom
        spectral_estimator #(.FFT_LOG2(FFT_LOG2),.OUT_WIDTH(OUT_WIDTH),
            .SAMPLE_RATE_HZ(FINE_FS),.COMPLEX_INPUT(1),.MIN_BIN(0),.MAX_BIN(N-1),
            .WINDOW_ENABLE(WINDOW_ENABLE)) u_fine (
            .clk(proc_clk),.rst_n(dsp_rst_n),.fft_re(fft_re),.fft_im(fft_im),.fft_bin(fft_bin),
            .fft_valid(fft_valid && fine_mode),.fft_last(fft_last && fine_mode),.frame_bad(frame_bad),
            .result_strobe(fine_strobe),.measurement_valid(fine_valid),.peak_bin(fine_peak),
            .bin_offset_q16(fine_delta),.frequency_offset_hz(fine_hz),
            .peak_power(fine_power),.noise_power(fine_noise),.interp_valid(fine_interp));
    end else begin: g_reliable
        assign fine_strobe=0; assign fine_valid=0; assign fine_interp=0;
        assign fine_peak=0; assign fine_delta=0; assign fine_hz=0;
        assign fine_power=0; assign fine_noise=0;
    end endgenerate
    wire low_strobe,low_valid,low_interp;
    wire [FFT_LOG2-1:0] low_peak;
    wire signed [17:0] low_delta;
    wire signed [31:0] low_hz;
    wire [2*OUT_WIDTH:0] low_power,low_noise;
    wire low_in_band=low_hz>=MIN_SIGNAL_HZ && low_hz<=LOW_BAND_MAX_HZ;
    generate if (ALGORITHM_VERSION==3) begin: g_low
        // Zero-NCO LPF + decimation, real FFT and frame-mean removal. Unlike
        // zoom, baseband DC is NOT a carrier and must not win the low-band peak.
        spectral_estimator #(.FFT_LOG2(FFT_LOG2),.OUT_WIDTH(OUT_WIDTH),
            .SAMPLE_RATE_HZ(FINE_FS),.WINDOW_ENABLE(WINDOW_ENABLE)) u_low (
            .clk(proc_clk),.rst_n(dsp_rst_n),.fft_re(fft_re),.fft_im(fft_im),.fft_bin(fft_bin),
            .fft_valid(fft_valid && low_mode),.fft_last(fft_last && low_mode),.frame_bad(frame_bad),
            .result_strobe(low_strobe),.measurement_valid(low_valid),.peak_bin(low_peak),
            .bin_offset_q16(low_delta),.frequency_offset_hz(low_hz),
            .peak_power(low_power),.noise_power(low_noise),.interp_valid(low_interp));
    end else begin: g_no_low
        assign low_strobe=0; assign low_valid=0; assign low_interp=0;
        assign low_peak=0; assign low_delta=0; assign low_hz=0;
        assign low_power=0; assign low_noise=0;
    end endgenerate
    wire [63:0] coarse_center_product=coarse_peak*{32'd0,ADC_SAMPLE_RATE_HZ[31:0]};
    reg [31:0] nco_center_hz;
    wire signed [32:0] recovered_hz=$signed({1'b0,nco_center_hz})+$signed(fine_hz);
    wire fine_in_band=(fine_hz>=-FINE_GUARD_HZ && fine_hz<=FINE_GUARD_HZ);
    wire recovered_in_band=ALGORITHM_VERSION==3 ?
        (recovered_hz>=MIN_SIGNAL_HZ && recovered_hz<ADC_SAMPLE_RATE_HZ/2) : recovered_hz>0;
    wire filtered_valid=low_mode ? (low_valid && low_in_band) :
        (fine_valid && fine_in_band && recovered_in_band);
    wire [31:0] filtered_frequency=low_mode ? low_hz : recovered_hz[31:0];
    wire [FFT_LOG2-1:0] filtered_peak=low_mode ? low_peak : fine_peak;
    wire signed [17:0] filtered_delta=low_mode ? low_delta : fine_delta;
    wire [2*OUT_WIDTH:0] filtered_power=low_mode ? low_power : fine_power;
    wire [2*OUT_WIDTH:0] filtered_noise=low_mode ? low_noise : fine_noise;
    wire [7:0] filtered_flags={1'b0,capture_bad,
        (low_mode ? !low_in_band : (!fine_in_band || !recovered_in_band)),1'b0,
        (low_mode ? low_interp : fine_interp),protocol_error,clipped_samples!=0,
        (low_mode ? !low_valid : !fine_valid)};
    reg [31:0] gap_counter,watchdog;
    reg timed_out;
    reg track_ready,track_fine,track_low,cycle_tracking;
    reg [31:0] track_frames,track_tuning_word,track_center_hz;
    // A cached low-pass path can alias a sudden high-frequency input back into
    // its passband. Validate each otherwise-valid tracking candidate against
    // a fresh short raw FFT before publishing it. This detects gross changes;
    // it is not a proof that the entire 4.096ms window was stationary.
    reg checking_result,pending_fine,pending_low;
    reg [31:0] pending_frequency,pending_tune,pending_center;
    reg [FFT_LOG2-1:0] pending_peak;
    reg signed [17:0] pending_delta;
    reg signed [31:0] pending_offset;
    reg [2*OUT_WIDTH:0] pending_power,pending_noise;
    reg [7:0] pending_flags;
    localparam integer COARSE_CHECK_MIN_HZ=300000;
    localparam integer COARSE_CHECK_TOL_HZ=(ADC_SAMPLE_RATE_HZ/N)*3/4+2;
    wire signed [32:0] coarse_difference=$signed({1'b0,pending_frequency})-$signed(coarse_hz);
    wire coarse_agrees=coarse_difference>=-COARSE_CHECK_TOL_HZ &&
        coarse_difference<=COARSE_CHECK_TOL_HZ;
    // A 16.384us raw record cannot resolve a few-kHz carrier; only use a
    // trusted high coarse peak as conflicting evidence for the low path.
    wire low_coarse_agrees=pending_frequency<COARSE_CHECK_MIN_HZ ?
        (!coarse_valid || coarse_hz<COARSE_CHECK_MIN_HZ || coarse_agrees) :
        (coarse_valid && coarse_agrees);
    wire postcheck_valid=!frame_bad && (pending_low ? low_coarse_agrees :
        (coarse_valid && coarse_in_band && coarse_agrees));
    always @(posedge proc_clk or negedge proc_rst_n) begin
        if (!proc_rst_n) begin
            state<=IDLE; capture_start<=0; capture_abort<=0; fine_mode<=0; low_mode<=0; core_reset_count<=15;
            tuning_word<=0; read_address<=0; product_i<=0; product_q<=0;
            stream_i<=0; stream_q<=0; gap_counter<=0; watchdog<=0; timed_out<=0;
            result_strobe<=0; measurement_valid<=0; frequency_hz<=0; sequence_number<=0;
            result_fine_mode<=0; result_low_mode<=0; tracking_active<=0; reacquire_count<=0;
            peak_bin<=0; coarse_bin<=0; bin_offset_q16<=0; fine_offset_hz<=0;
            peak_power<=0; noise_power<=0; result_flags<=0; nco_center_hz<=0;
            track_ready<=0; track_fine<=0; track_low<=0; cycle_tracking<=0;
            track_frames<=0; track_tuning_word<=0; track_center_hz<=0;
            checking_result<=0; pending_fine<=0; pending_low<=0;
            pending_frequency<=0; pending_tune<=0; pending_center<=0; pending_peak<=0;
            pending_delta<=0; pending_offset<=0; pending_power<=0; pending_noise<=0; pending_flags<=0;
        end else begin
            capture_start<=0; capture_abort<=0; result_strobe<=0;
            if (core_reset_count!=0) core_reset_count<=core_reset_count-1;
            if (state==WAIT_CAPTURE || state==PRIME || state==MULTIPLY || state==ROUND ||
                state==SEND || state==WAIT_RESULT) watchdog<=watchdog+1;
            case(state)
                IDLE: begin
                    if (!enabled) begin track_ready<=0; track_frames<=0; end
                    if (gap_counter!=0) gap_counter<=gap_counter-1;
                    else if (enabled && configured && !capture_busy) begin
                        if (TRACKING_ENABLE && ALGORITHM_VERSION==3 && track_ready &&
                            track_frames<TRACK_RECHECK_FRAMES) begin
                            fine_mode<=track_fine; low_mode<=track_low;
                            tuning_word<=track_tuning_word; nco_center_hz<=track_center_hz;
                            cycle_tracking<=1; track_frames<=track_frames+1;
                        end else begin
                            fine_mode<=0; low_mode<=0; tuning_word<=0;
                            cycle_tracking<=0; track_ready<=0; track_frames<=0;
                            reacquire_count<=reacquire_count+1;
                        end
                        timed_out<=0; checking_result<=0; state<=START_CAPTURE;
                    end
                end
                START_CAPTURE: begin capture_start<=1; watchdog<=0; state<=WAIT_CAPTURE; end
                WAIT_CAPTURE: if (capture_done) begin
                    read_address<=0; state<=PRIME;
                end
                PRIME: state<=MULTIPLY;
                MULTIPLY: begin product_i<=adjusted_i*hann_q; product_q<=adjusted_q*hann_q; state<=ROUND; end
                ROUND: begin
                    stream_i<=WINDOW_ENABLE ? ((product_i+32'sd16384)>>>15) : adjusted_i;
                    stream_q<=WINDOW_ENABLE ? ((product_q+32'sd16384)>>>15) : adjusted_q;
                    state<=SEND;
                end
                SEND: if (sample_ready) begin
                    if (read_address==N-1) state<=WAIT_RESULT;
                    else begin read_address<=read_address+1; state<=PRIME; end
                end
                WAIT_RESULT: begin
                    if (!fine_mode && !low_mode && coarse_strobe) begin
                        if (checking_result) begin
                            frequency_hz<=postcheck_valid ? pending_frequency : 0;
                            measurement_valid<=postcheck_valid;
                            peak_bin<=pending_peak; bin_offset_q16<=pending_delta; fine_offset_hz<=pending_offset;
                            peak_power<=pending_power; noise_power<=pending_noise;
                            // Bit6 means an unusable capture/window, including a
                            // fresh raw/filtered-frequency consistency failure.
                            result_flags<=pending_flags | (postcheck_valid ? 8'h00 : 8'h40) |
                                (protocol_error ? 8'h04 : 8'h00) |
                                (clipped_samples!=0 ? 8'h02 : 8'h00);
                            fine_mode<=pending_fine; low_mode<=pending_low;
                            tuning_word<=pending_tune; nco_center_hz<=pending_center;
                            checking_result<=0; state<=PUBLISH;
                        end else if (coarse_valid && coarse_in_band &&
                            ((ALGORITHM_VERSION==2 && coarse_peak>=ZOOM_MIN_BIN) ||
                             (ALGORITHM_VERSION==3 && coarse_hz>=HIGH_BAND_MIN_HZ))) begin
                            coarse_bin<=coarse_peak;
                            tuning_word<=coarse_peak<<(32-FFT_LOG2);
                            nco_center_hz<=(coarse_center_product+N/2)>>FFT_LOG2;
                            fine_mode<=1; state<=START_CAPTURE;
                        end else if (ALGORITHM_VERSION==3 && !frame_bad) begin
                            coarse_bin<=coarse_peak;
                            // A short raw frame cannot resolve low carriers. Gather
                            // NEW samples over 4.096ms; never reuse/zero-pad that frame.
                            tuning_word<=0; low_mode<=1; fine_mode<=0; state<=START_CAPTURE;
                        end else begin
                            coarse_bin<=coarse_peak;
                            peak_bin<=coarse_peak; bin_offset_q16<=coarse_delta; fine_offset_hz<=0;
                            peak_power<=coarse_power; noise_power<=coarse_noise;
                            measurement_valid<=coarse_valid && coarse_in_band && ALGORITHM_VERSION==1;
                            frequency_hz<=(coarse_valid && coarse_in_band && ALGORITHM_VERSION==1) ? coarse_hz : 0;
                            result_flags<={1'b0,capture_bad,(!coarse_in_band || ALGORITHM_VERSION==2),1'b0,coarse_interp,
                                protocol_error,clipped_samples!=0,!coarse_valid};
                            state<=PUBLISH;
                        end
                    end else if ((low_mode && low_strobe) || (fine_mode && fine_strobe)) begin
                        if (TRACKING_ENABLE && ALGORITHM_VERSION==3 && filtered_valid) begin
                            pending_frequency<=filtered_frequency; pending_peak<=filtered_peak;
                            pending_delta<=filtered_delta; pending_offset<=low_mode ? 0 : fine_hz;
                            pending_power<=filtered_power; pending_noise<=filtered_noise; pending_flags<=filtered_flags;
                            pending_fine<=fine_mode; pending_low<=low_mode;
                            pending_tune<=tuning_word; pending_center<=nco_center_hz;
                            checking_result<=1; fine_mode<=0; low_mode<=0; tuning_word<=0;
                            state<=START_CAPTURE;
                        end else begin
                            peak_bin<=filtered_peak; bin_offset_q16<=filtered_delta;
                            fine_offset_hz<=low_mode ? 0 : fine_hz;
                            peak_power<=filtered_power; noise_power<=filtered_noise;
                            measurement_valid<=filtered_valid;
                            frequency_hz<=filtered_valid ? filtered_frequency : 0;
                            result_flags<=filtered_flags; state<=PUBLISH;
                        end
                    end
                end
                PUBLISH: begin
                    // Result metadata remains attached to the published frame
                    // after the working FFT modes advance to the next capture.
                    result_fine_mode<=fine_mode; result_low_mode<=low_mode;
                    tracking_active<=cycle_tracking;
                    if (TRACKING_ENABLE && ALGORITHM_VERSION==3 && measurement_valid &&
                        (fine_mode || low_mode) &&
                        (!fine_mode || (fine_offset_hz>-TRACK_EDGE_HZ && fine_offset_hz<TRACK_EDGE_HZ))) begin
                        track_ready<=1; track_fine<=fine_mode; track_low<=low_mode;
                        track_tuning_word<=tuning_word; track_center_hz<=nco_center_hz;
                    end else begin track_ready<=0; track_frames<=0; end
                    result_strobe<=1; sequence_number<=sequence_number+1;
                    gap_counter<=FRAME_GAP_CYCLES; state<=IDLE;
                end
                RECOVER: if (!capture_busy && core_reset_count==0) begin gap_counter<=FRAME_GAP_CYCLES; state<=IDLE; end
                default: state<=IDLE;
            endcase
            // Stopped ADC clock can never complete a capture; publish invalid once,
            // request abort and wait for ADC clock to return rather than reading live RAM.
            if (!timed_out && watchdog>=TIMEOUT_CYCLES &&
                (state==WAIT_CAPTURE || state==PRIME || state==MULTIPLY ||
                 state==ROUND || state==SEND || state==WAIT_RESULT)) begin
                timed_out<=1; capture_abort<=1; measurement_valid<=0; frequency_hz<=0;
                result_flags<=8'h11; result_strobe<=1; sequence_number<=sequence_number+1;
                result_fine_mode<=fine_mode; result_low_mode<=low_mode; tracking_active<=cycle_tracking;
                track_ready<=0; track_frames<=0;
                checking_result<=0;
                peak_bin<=0; bin_offset_q16<=0; fine_offset_hz<=0; peak_power<=0; noise_power<=0;
                // Flush partial FFT/postscan before resuming after ADC clock returns.
                core_reset_count<=15;
                state<=RECOVER;
            end
        end
    end
endmodule
